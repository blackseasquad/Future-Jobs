#!/usr/bin/env node
// Builds api/_data/esco-map.js — the ESCO skill → occupation → ISCO-08 mapping used by the daily refresh.
//
// Why a bundled file: the ESCO API answers HTTP 403 to requests from Vercel's servers, so the production
// function cannot query it. ESCO changes only with new releases (1–2 per year), so the mapping is built
// here (GitHub Actions: .github/workflows/esco-map.yml, or locally) and shipped with the code.
//
// Usage: node scripts/build-esco-map.mjs [--out api/_data/esco-map.js]

import { writeFileSync } from 'node:fs';
import { SKILLS } from '../api/_lib/catalog.js';
import { escoFindSkill, escoOccupationDetails, escoSkillDetails } from '../api/_lib/sources.js';

const out = process.argv.includes('--out') ? process.argv[process.argv.indexOf('--out') + 1] : 'api/_data/esco-map.js';

async function retry(fn, tries = 4) {
  for (let i = 0; ; i++) {
    try { return await fn(); } catch (e) {
      if (i >= tries - 1) throw e;
      await new Promise((r) => setTimeout(r, 1000 * 2 ** i));
    }
  }
}

async function mapLimit(items, limit, fn) {
  let i = 0;
  await Promise.all(Array.from({ length: limit }, async () => { while (i < items.length) { const it = items[i++]; await fn(it); } }));
}

const skills = {};
const errors = [];
for (const s of SKILLS) {
  try {
    const hit = s.escoUri ? { uri: s.escoUri } : await retry(() => escoFindSkill(s.esco));
    if (!hit) { errors.push(`${s.id}: no ESCO match for "${s.esco}"`); continue; }
    const d = await retry(() => escoSkillDetails(hit.uri));
    skills[s.id] = {
      uri: d.uri, label_en: d.label_en, label_bg: d.label_bg, alt_en: d.alt_en.slice(0, 40),
      occupations: d.occupations.map((o) => ({ uri: o.uri, relation: o.relation })),
    };
    console.log(`${s.id.padEnd(22)} -> ${d.label_en} (${d.occupations.length} occupations)`);
  } catch (e) {
    errors.push(`${s.id}: ${e.message}`);
  }
}

const occUris = [...new Set(Object.values(skills).flatMap((s) => s.occupations.map((o) => o.uri)))];
const occupations = {};
await mapLimit(occUris, 6, async (uri) => {
  try {
    const d = await retry(() => escoOccupationDetails(uri));
    occupations[uri] = { label_en: d.label_en, label_bg: d.label_bg, isco_code: d.isco_code, isco2: d.isco2 };
  } catch (e) {
    errors.push(`occupation ${uri}: ${e.message}`);
  }
});

const missing = SKILLS.length - Object.keys(skills).length;
const withIsco = Object.values(occupations).filter((o) => o.isco2).length;
console.log(`\nskills: ${Object.keys(skills).length}/${SKILLS.length}, occupations: ${Object.keys(occupations).length}/${occUris.length}, with ISCO: ${withIsco}`);
errors.forEach((e) => console.warn('warn:', e));
if (missing > SKILLS.length / 4 || withIsco < occUris.length * 0.8) {
  console.error('Too many failures — not writing the file.');
  process.exit(1);
}

const sorted = (obj) => Object.fromEntries(Object.keys(obj).sort().map((k) => [k, obj[k]]));
try {
  const { pathToFileURL } = await import('node:url');
  const { resolve } = await import('node:path');
  const prev = (await import(pathToFileURL(resolve(out)).href)).default;
  if (JSON.stringify({ s: prev.skills, o: prev.occupations }) === JSON.stringify({ s: sorted(skills), o: sorted(occupations) })) {
    console.log('ESCO data unchanged — keeping the existing file.');
    process.exit(0);
  }
} catch { /* no previous file */ }
const data = { generatedAt: new Date().toISOString(), source: 'ESCO API (https://ec.europa.eu/esco/api)', skills: sorted(skills), occupations: sorted(occupations) };
writeFileSync(out, `// Generated by scripts/build-esco-map.mjs — do not edit by hand.\n// ESCO © European Union, reused under Commission Decision 2011/833/EU.\nexport default ${JSON.stringify(data, null, 1)};\n`);
console.log(`written ${out}`);
